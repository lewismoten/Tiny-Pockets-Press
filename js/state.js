TPP.bookInfoFieldValue = function (book, fieldKey, options) {
  const dateFormat = (options && options.dateFormat) || "year-month-day";
  if (String(fieldKey || "").startsWith("custom:")) {
    const id = String(fieldKey).slice("custom:".length);
    const entry = TPP.bookInfo(book).find(function (item) {
      return item && item.id === id;
    });
    return String((entry && entry.value) || "");
  }
  if (String(fieldKey || "").startsWith("classification:")) {
    const formatId = String(fieldKey).slice("classification:".length).trim();
    const rawValue = String(TPP.bookInfoValue(book, "classification") || "");
    if (!rawValue) return "";
    if (
      typeof TPP.classificationValueData === "function" &&
      typeof TPP.classificationDisplayString === "function"
    ) {
      const data = TPP.classificationValueData(rawValue);
      return TPP.classificationDisplayString(
        book,
        Object.assign({}, data, {
          formatId: formatId || data.formatId || "",
        }),
      );
    }
    return rawValue;
  }
  if (String(fieldKey || "").startsWith("author:")) {
    return TPP.authorFieldVariantValue(book, fieldKey, options);
  }
  if (String(fieldKey || "").startsWith("pubDate:")) {
    return TPP.pubDateFieldVariantValue(book, fieldKey);
  }
  if (fieldKey === "series")
    return [
      TPP.bookInfoValue(book, "seriesName"),
      TPP.bookInfoValue(book, "number"),
    ]
      .filter(Boolean)
      .join(" ");
  if (fieldKey === "author")
    return options && options.location === "spine"
      ? String(
          TPP.authorCompactSummary(TPP.bookInfoValue(book, "author")) || "",
        )
      : TPP.authorListText(TPP.bookInfoValue(book, "author"), {
          includeRoles: false,
        });
  if (fieldKey === "pubDate")
    return TPP.formatBookDate(
      TPP.bookInfoValue(book, "pubDate"),
      dateFormat === "month-day-year" ? "year-month-day" : dateFormat,
    );
  if (fieldKey === "custom")
    return String((options && options.customText) || "");
  return String(TPP.bookInfoValue(book, fieldKey) || "");
};
