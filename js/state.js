TPP.authorFieldVariantValue = function (book, fieldKey, options) {
  const variant = TPP.parseAuthorFieldVariant(fieldKey);
  if (!variant) return "";
  let list = TPP.authorEntriesFromValue(TPP.bookInfoValue(book, "author"));
  if (variant.role) {
    list = list.filter(function (entry) {
      return (
        String((entry && entry.role) || "author")
          .trim()
          .toLowerCase() === variant.role
      );
    });
  }
  if (!list.length) return "";
  if (variant.format === "inverted") {
    return TPP.authorListText(list, {
      inverted: "all",
      includeRoles: false,
    });
  }
  if (variant.format === "inverted-initials") {
    return TPP.authorListText(list, {
      inverted: "all",
      initials: true,
      includeRoles: false,
    });
  }
  if (options && options.location === "spine" && !variant.role) {
    return TPP.authorCompactSummary(list);
  }
  return TPP.authorListText(list, { includeRoles: false });
};
TPP.normalizeBookInfoEntries = function (book) {
  const source = book && book.bookInfo;
  const legacyClassificationResolutions =
    book &&
    book.meta &&
    book.meta.classificationResolutions &&
    typeof book.meta.classificationResolutions === "object"
      ? book.meta.classificationResolutions
      : {};
  let legacyLocale = { language: "", region: "" };
  const normalizeClassificationValue = function (rawValue, metaText) {
    const value = String(rawValue || "");
    const extraMeta = String(metaText || "");
    if (!value) return "";
    try {
      const parsed = JSON.parse(value);
      if (parsed && typeof parsed === "object") {
        const normalized = {
          code: String(parsed.code || ""),
          shortLabel: String(parsed.shortLabel || ""),
          formatId: String(parsed.formatId || ""),
          extension: String(parsed.extension || ""),
          title: String(parsed.title || ""),
          meta: String(parsed.meta || extraMeta || ""),
        };
        return JSON.stringify(normalized);
      }
    } catch (_error) {}
    return value;
  };
  let entries = [];
  if (Array.isArray(source)) {
    entries = source
      .map(function (entry, index) {
        if (!entry || typeof entry !== "object") return null;
        if (entry.key === "languageCountry") {
          const parsedLocale = TPP.parseLocaleParts(entry.value);
          legacyLocale = {
            language: legacyLocale.language || parsedLocale.language || "",
            region: legacyLocale.region || parsedLocale.region || "",
          };
          return null;
        }
        const key = TPP.BOOK_INFO_FIELDS.includes(entry.key)
          ? entry.key
          : entry.key === "custom"
            ? "custom"
            : "";
        if (!key) return null;
        const resolution =
          key === "classification"
            ? entry.classificationSummary ||
              legacyClassificationResolutions[
                entry.id || TPP.bookInfoEntryId(key, index + 1)
              ]
            : null;
        const classificationValue =
          key === "classification"
            ? (function () {
                const normalizedValue = normalizeClassificationValue(
                  entry.value,
                  resolution && resolution.meta,
                );
                if (!normalizedValue) return "";
                try {
                  const parsed = JSON.parse(normalizedValue);
                  if (parsed && typeof parsed === "object") {
                    parsed.title = String(
                      parsed.title ||
                        entry.customLabel ||
                        (resolution && resolution.title) ||
                        "",
                    );
                    return JSON.stringify(parsed);
                  }
                } catch (_error) {}
                return normalizedValue;
              })()
            : String(entry.value || "");
        return {
          id: entry.id || TPP.bookInfoEntryId(key, index + 1),
          key: key,
          value: classificationValue,
          customLabel:
            key === "classification" ? "" : String(entry.customLabel || ""),
        };
      })
      .filter(Boolean);
  } else {
    const objectSource = source && typeof source === "object" ? source : {};
    legacyLocale = TPP.parseLocaleParts(objectSource.languageCountry || "");
    entries = TPP.BOOK_INFO_FIELDS.filter(function (key) {
      return (
        TPP.BOOK_INFO_DEFAULT_FIELDS.includes(key) ||
        String(objectSource[key] || "").trim()
      );
    }).map(function (key, index) {
      return {
        id: TPP.bookInfoEntryId(key, index + 1),
        key: key,
        value: String(objectSource[key] || ""),
        customLabel: "",
      };
    });
  }
  const defaults = TPP.bookInfoDefaults();
  const byKey = new Map();
  entries.forEach(function (entry) {
    if (entry.key === "spineAuthor") return;
    if (entry.key === "custom") return;
    if (!byKey.has(entry.key)) byKey.set(entry.key, entry);
  });
  const normalized = defaults.map(function (entry) {
    const existing = byKey.get(entry.key);
    if (existing) {
      return Object.assign({}, entry, existing, {
        id: existing.id || entry.id,
      });
    }
    if (entry.key === "language" && legacyLocale.language) {
      return Object.assign({}, entry, { value: legacyLocale.language });
    }
    if (entry.key === "region" && legacyLocale.region) {
      return Object.assign({}, entry, { value: legacyLocale.region });
    }
    return Object.assign({}, entry);
  });
  TPP.BOOK_INFO_FIELDS.forEach(function (key) {
    if (TPP.BOOK_INFO_DEFAULT_FIELDS.includes(key) || !byKey.has(key)) return;
    normalized.push(byKey.get(key));
  });
  entries.forEach(function (entry) {
    if (entry.key === "custom") normalized.push(entry);
  });
  if (
    book &&
    book.meta &&
    book.meta.classificationResolutions &&
    typeof book.meta.classificationResolutions === "object"
  ) {
    delete book.meta.classificationResolutions;
  }
  return normalized;
};
