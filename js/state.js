TPP.formatBookDate = function (value, mode) {
  if (!value) return "";
  const date = new Date(value + "T12:00:00");
  if (Number.isNaN(date.getTime())) return "";
  if (mode === "year") return String(date.getFullYear());
  if (mode === "year-month")
    return date.toLocaleDateString(undefined, {
      year: "numeric",
      month: "long",
    });
  return date.toLocaleDateString(undefined, {
    year: "numeric",
    month: "long",
    day: "numeric",
  });
};
